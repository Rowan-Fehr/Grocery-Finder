"""Local demo: search a recipe, click it, pictures are made live by Gemini.
Your key stays in this program (config.json); the web page never sees it.
Only reachable from your own PC (127.0.0.1)."""
import json, os, sys, time, threading, urllib.error
from http.server import ThreadingHTTPServer, BaseHTTPRequestHandler
import generate_step_images as g
import imgtools
from step_prompt import build_prompt  # noqa

HERE = os.path.dirname(os.path.abspath(__file__))
KEY = g.load_key()
RECIPES = json.load(open(os.path.join(HERE, "recipes.json"), encoding="utf-8"))
CACHE = os.path.join(HERE, "images")
PORT = 8000

def find(rid):
    return next((r for r in RECIPES if str(r["id"]) == rid), None)

class H(BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def send(self, code, body, ctype, extra=None):
        self.send_response(code); self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        for k, v in (extra or {}).items(): self.send_header(k, v)
        self.end_headers(); self.wfile.write(body)
    def do_GET(self):
        if self.path in ("/", "/index.html"):
            self.send(200, open(os.path.join(HERE, "demo.html"), "rb").read(), "text/html; charset=utf-8")
        elif self.path.startswith("/img/"):
            try:
                _, _, rid, n = self.path.split("?")[0].split("/"); n = int(n)
            except Exception:
                return self.send(400, b"bad", "text/plain")
            for p, ct in ((imgtools.small_path(HERE, rid, n), "image/jpeg"), (imgtools.big_path(HERE, rid, n), "image/png")):
                if os.path.exists(p):
                    return self.send(200, open(p, "rb").read(), ct, {"Cache-Control": "max-age=3600", "X-Source": "saved"})
            self.send(404, b"not saved yet", "text/plain")
        elif self.path == "/api/ping":
            self.send(200, b"ok", "text/plain", {"Cache-Control": "no-store"})
        elif self.path == "/api/recipes":
            self.send(200, json.dumps(RECIPES).encode(), "application/json")
        else:
            self.send(404, b"not found", "text/plain")
    def do_POST(self):
        if self.path != "/api/step":
            return self.send(404, b"not found", "text/plain")
        d = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))))
        r = find(str(d.get("id"))); n = int(d.get("n", 1))
        if not r or n < 1 or n > len(r["steps"]):
            return self.send(400, b"bad request", "text/plain")
        path = os.path.join(CACHE, str(r["id"]), "step-%d.png" % n)
        t0 = time.time()
        try:
            png = g.generate(KEY, r.get("title", ""), g.step_text(r["steps"][n-1]), n, len(r["steps"]))
        except urllib.error.HTTPError as e:
            return self.send(502, ("Gemini error %s: %s" % (e.code, e.read().decode(errors="replace")[:200])).encode(), "text/plain")
        except Exception as e:
            return self.send(502, ("Error: %s" % e).encode(), "text/plain")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "wb").write(png)
        small = imgtools.shrink_bytes(png)
        if small: imgtools.save_small(HERE, r["id"], n, png)
        self.send(200, small or png, "image/jpeg" if small else "image/png", {"X-Ms": str(int((time.time()-t0)*1000)), "X-Source": "gemini"})

def self_check():
    """Runs at startup so problems show up here in plain words."""
    problems = []
    html = open(os.path.join(HERE, "demo.html"), encoding="utf-8").read()
    for bad in ("Make fresh pictures", "Make pictures live", "Making picture", "generated by", "Gemini"):
        if bad.lower() in html.lower():
            problems.append("demo.html still contains the old text: '%s' (the file did not update)" % bad)
    for r in RECIPES:
        if not r.get("id") or not r.get("steps"):
            problems.append("a recipe in recipes.json is missing an id or steps")
        saved = sum(os.path.exists(imgtools.big_path(HERE, r["id"], n)) for n in range(1, len(r["steps"]) + 1))
        print("  %s: %d/%d pictures saved" % (r.get("title", r.get("id")), saved, len(r["steps"])))
    if imgtools.Image is None:
        problems.append("Pillow is not installed, so pictures will load slower")
    print("  Self-check:", "ALL GOOD" if not problems else "PROBLEMS FOUND")
    for p in problems: print("   - " + p)

def prepare_small():
    if imgtools.Image is None:
        print("Note: Pillow not installed, pictures will stay big (slower).")
        return
    for r in RECIPES:
        for n in range(1, len(r["steps"]) + 1):
            b, sm = imgtools.big_path(HERE, r["id"], n), imgtools.small_path(HERE, r["id"], n)
            if os.path.exists(b) and not os.path.exists(sm):
                imgtools.save_small(HERE, r["id"], n, open(b, "rb").read())

if __name__ == "__main__":
    prepare_small()
    self_check()
    print("Demo running at http://localhost:%d  (close this window to stop)" % PORT)
    ThreadingHTTPServer(("127.0.0.1", PORT), H).serve_forever()
